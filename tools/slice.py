# whole-sheet assets (no cropping)
WHOLE = {"WM": "137:1477", "HEALTH": "244:1536"}

# cafe branding: 10 equal columns
CAFE_COLS = 10

ZONE = {}
for line in open(os.path.join(BUILD, "manifest.tsv")):
    p = line.rstrip("\n").split("\t")
    if len(p) >= 2:
        ZONE[p[0]] = p[1]

def save(im, node_id, zone):
    d = os.path.join(OUT, zone)
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, node_id.replace(":", "-") + ".png")
    if im.mode == "RGBA":
        bg = Image.new("RGB", im.size, (255, 255, 255))
        bg.paste(im, mask=im.split()[3])
        im = bg
    im.save(path, "PNG", optimize=False)
    return path

written = []
for sheet, (ow, oh, items) in CROPS.items():
    src = Image.open(os.path.join(SHEETS, sheet + ".png"))
    sx, sy = src.width / ow, src.height / oh
    for nid, x, y, w, h in items:
        box = (round(x * sx), round(y * sy), round((x + w) * sx), round((y + h) * sy))
        box = (max(0, box[0]), max(0, box[1]), min(src.width, box[2]), min(src.height, box[3]))
        crop = src.crop(box)
        written.append((nid, save(crop, nid, ZONE.get(nid, "misc")), crop.size))
    src.close()

for sheet, nid in WHOLE.items():
    im = Image.open(os.path.join(SHEETS, sheet + ".png"))
    written.append((nid, save(im, nid, ZONE.get(nid, "misc")), im.size))
    im.close()

# cafe branding sheet -> 10 slides
cafe = Image.open(os.path.join(SHEETS, "CAFE.png"))
cw = cafe.width / CAFE_COLS
for i in range(CAFE_COLS):
    crop = cafe.crop((round(i * cw), 0, round((i + 1) * cw), cafe.height))
    nid = "3:17-%02d" % (i + 1)
    written.append((nid, save(crop, nid, "branding"), crop.size))
cafe.close()

print("wrote", len(written), "files")
missing = set(ZONE) - {w[0] for w in written} - {"3:17"}
print("missing:", sorted(missing) if missing else "none")
